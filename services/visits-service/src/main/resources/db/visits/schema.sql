-- Visits bounded context. The owner_id is denormalised on purpose: it is what customers-service
-- validated when the visit was booked, and it keeps queries scoped by owner (BR-VIS-03).
DROP TABLE IF EXISTS visits;

CREATE TABLE visits (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id    INTEGER NOT NULL,
  pet_id      INTEGER NOT NULL,
  visit_date  DATE NOT NULL,
  description VARCHAR(255) NOT NULL
);
CREATE INDEX visits_pet_id ON visits (pet_id);
CREATE INDEX visits_owner_id ON visits (owner_id);
